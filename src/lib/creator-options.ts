export function durationLabel(seconds: number): string {
  return DURATIONS.find((d) => d.value === seconds)?.label ?? `${Math.round(seconds / 60)} minutes`;
}

/** Rough spoken-word budget used to steer script length. ~140 words per minute. */
export function wordBudget(seconds: number): number {
  return Math.round((seconds / 60) * 140);
}
